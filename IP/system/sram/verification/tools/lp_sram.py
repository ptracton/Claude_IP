#!/usr/bin/env python3
"""lp_sram.py — Static low-power (UPF) checks of the sram IP with VC LP (Step 10).

Reads the SV RTL of a top-level with the PDK's standard-cell and SRAM macro
libraries (the same .db files as synthesis), loads design/upf/sram_<pdk>.upf
for the configuration, and runs VC LP:
    check_lp -stage upf      UPF consistency: domains, supplies, power switch,
                             isolation strategy, power state table
    check_lp -stage design   architecture against the UPF: crossings out of a
                             switched domain without an isolation strategy,
                             control signals, supply states
At RTL no isolation cell exists yet (synthesis inserts them), so two
design-stage tags are expected and not counted (RTL_EXPECTED below); every
other error fails the run. Warnings are listed.

Configurations (the DC netlists' parameters, see synthesis/run_vendor_synth.py):
    base  sram_apb     one power domain (NPD 1, 1 bank)
    opts  sram_apb     ECC, BANK_PG, NUM_BANKS 2, BIST, RL2   (NPD 2)
    dp    sram_apb_dp  opts + WIDTH_B 8, COMMON_CLK 0 (SAED14: 1)
The UPF is scoped at the top-level and names only u_core's array and power
controllers, which every bus top shares, so APB stands for the four buses.

Usage:
    python3 lp_sram.py                        # 4 PDKs x 3 configurations
    python3 lp_sram.py --pdk saed90 --cfg opts
    python3 lp_sram.py --jobs 2               # vc_static_shell runs in parallel (max 3)

Outputs:
    verification/work/lp/<pdk>_<cfg>/{lp.tcl,vclp.log,lp_report.txt}
    verification/lp/lp_results.log
"""

import argparse
import os
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import lint_sram  # noqa: E402  (RTL file list)

PDKS = ["saed90", "saed32", "saed14", "sky130"]
CFGS = ["base", "opts", "dp"]
TECH_NUM = {"saed90": 3, "saed32": 4, "saed14": 5, "sky130": 6}
OPTS = {"ECC_EN": 1, "BANK_PG": 1, "NUM_BANKS": 2, "BIST_EN": 1, "READ_LATENCY": 2}
MAX_JOBS = 3

# Design-stage tags that only say "no isolation cell inserted yet" at RTL.
RTL_EXPECTED = {
    "ISO_INST_MISSING": "isolation required and covered by a strategy; the cell is inserted by synthesis",
    "ISO_STRATEGY_UNUSED": "strategy not yet implemented by a cell (RTL)",
}


def ip_path() -> str:
    p = os.environ.get("CLAUDE_SRAM_PATH")
    if not p:
        print("ERROR: CLAUDE_SRAM_PATH is not set. Run: source IP/system/sram/setup.sh")
        sys.exit(1)
    return p


def libraries(pdk: str) -> tuple:
    """(search_path, link_library) — the libraries synthesis links."""
    sys.path.insert(0, os.path.join(ip_path(), "synthesis"))
    import run_vendor_synth as rvs  # noqa: E402
    import glob
    if pdk == "saed90":
        std = f"{rvs.SAED90_PDK}/Digital_Standard_cell_Library/synopsys/models/saed90nm_max.db"
        macros = sorted(glob.glob(f"{rvs.SAED90_PDK}/Memories/synopsys/models/SRAM*_max.db"))
    elif pdk == "saed32":
        std = f"{rvs.SAED32_EDK}/lib/stdcell_rvt/db_nldm/saed32rvt_ss0p95v125c.db"
        macros = [rvs.build_saed32_sram_libs.ensure_saed32_sram_db("ss0p95v125c_i0p95v")]
    elif pdk == "saed14":
        std = f"{rvs.SAED14_EDK}/SAED14nm_EDK_STD_RVT/liberty/nldm/base/saed14rvt_base_ss0p72v125c.db"
        macros = [f"{rvs.SAED14_EDK}/SAED14nm_EDK_SRAM/liberty/nldm/saed14sram_ss0p72v125c.db"]
    else:
        b = rvs.build_sky130_libs
        std = b.ensure_sky130_dbs(b.SKY130_PDK)[b.SKY130_SYNTH_CORNER]
        macros = list(b.ensure_sky130_sram_dbs(b.SKY130_PDK))
    files = [std] + macros
    missing = [f for f in files if not f or not os.path.isfile(f)]
    if missing:
        raise FileNotFoundError(f"{pdk} libraries missing: {missing}")
    dirs = sorted({os.path.dirname(f) for f in files})
    return dirs, [os.path.basename(f) for f in files]


def config(pdk: str, cfg: str) -> tuple:
    """(top, parameter dict, NPD, NUM_BANKS)."""
    params = {"TECH": TECH_NUM[pdk]}
    if cfg == "base":
        return "sram_apb", params, 1, 1
    params.update(OPTS)
    if cfg == "opts":
        return "sram_apb", params, 2, 2
    params.update({"WIDTH_B": 8, "COMMON_CLK": 1 if pdk == "saed14" else 0})
    return "sram_apb_dp", params, 2, 2


def write_tcl(pdk: str, cfg: str, work: str) -> str:
    ip = ip_path()
    top, params, npd, banks = config(pdk, cfg)
    dirs, libs = libraries(pdk)
    files = lint_sram.sv_files(ip, "apb", top)
    pv = " ".join(f"-pvalue+{top}.{k}={v}" for k, v in params.items())
    upf = os.path.join(ip, "design", "upf", f"sram_{pdk}.upf")
    tcl = os.path.join(work, "lp.tcl")
    with open(tcl, "w") as fh:
        fh.write(f"""# lp.tcl — GENERATED by verification/tools/lp_sram.py ({pdk} {cfg}). Do not edit.
set_app_var enable_lp base
set_app_var search_path [list . {' '.join(dirs)}]
set_app_var link_library [list {' '.join(libs)}]
analyze -format sverilog -vcs "-sverilog {' '.join(files)}"
elaborate {top} -vcs "{pv}"
set SRAM_NPD       {npd}
set SRAM_NUM_BANKS {banks}
read_upf {upf}
check_lp -stage upf
check_lp -stage design
report_lp -verbose -file lp_report.txt
puts "LP_DONE"
quit
""")
    return tcl


# Tree Summary row; a trailing "*" marks a count past the report's message limit.
_ROW_RE = re.compile(r"^\s*(error|warning|info)\s+(\S+)\s+(\S+)\s+(\d+)\s*\*?\s*$")
_MGMT_TOTAL_RE = re.compile(r"^\s*Total\s+(\d+)\s+(\d+)\s+(\d+)\s*$")


def management_errors(path: str) -> int:
    """Total errors in report_lp's Management Summary (-1 if not found)."""
    on = False
    for line in open(path):
        if "Management Summary" in line:
            on = True
        elif on:
            m = _MGMT_TOTAL_RE.match(line)
            if m:
                return int(m.group(1))
            if "Tree Summary" in line:
                break
    return -1


def parse_report(path: str) -> list:
    """[(severity, stage, tag, count)] from report_lp's Tree Summary."""
    rows, on = [], False
    if not os.path.isfile(path):
        return rows
    for line in open(path):
        if "Tree Summary" in line:
            on = True
            continue
        if on:
            m = _ROW_RE.match(line)
            if m:
                rows.append((m.group(1), m.group(2), m.group(3), int(m.group(4))))
            elif line.strip().startswith("Total"):
                break
    return rows


def run_one(pdk: str, cfg: str) -> tuple:
    """Returns (pdk, cfg, status, detail)."""
    work = os.path.join(ip_path(), "verification", "work", "lp", f"{pdk}_{cfg}")
    os.makedirs(work, exist_ok=True)
    for f in ("lp_report.txt", "vclp.log"):
        if os.path.exists(os.path.join(work, f)):
            os.remove(os.path.join(work, f))
    try:
        tcl = write_tcl(pdk, cfg, work)
    except (FileNotFoundError, KeyError, TypeError) as e:
        return pdk, cfg, "FAIL", f"setup: {e}"
    log = os.path.join(work, "vclp.log")
    print(f"  [lp/{pdk}/{cfg}] running VC LP ...", flush=True)
    try:
        with open(log, "w") as fh:
            subprocess.run(["vc_static_shell", "-f", tcl, "-no_ui"], cwd=work, stdout=fh,
                           stderr=subprocess.STDOUT, timeout=3600)
    except FileNotFoundError:
        return pdk, cfg, "FAIL", "vc_static_shell not found"
    except subprocess.TimeoutExpired:
        return pdk, cfg, "FAIL", "timeout"
    text = open(log, errors="ignore").read()
    if "LP_DONE" not in text:
        errs = [ln.strip() for ln in text.splitlines() if "[Error]" in ln or ln.startswith("Error")]
        return pdk, cfg, "FAIL", "VC LP did not finish: " + "; ".join(errs[:3])
    rpt = os.path.join(work, "lp_report.txt")
    rows = parse_report(rpt)
    if not os.path.isfile(rpt):
        return pdk, cfg, "FAIL", "no lp_report.txt"
    # The tag rows must account for every error of the summary (a format
    # surprise must not read as a clean run).
    mgmt = management_errors(rpt)
    parsed = sum(r[3] for r in rows if r[0] == "error")
    if mgmt != parsed:
        return pdk, cfg, "FAIL", f"report parse mismatch: {mgmt} errors in summary, {parsed} in tags"
    errors = [r for r in rows if r[0] == "error" and r[2] not in RTL_EXPECTED]
    expected = [r for r in rows if r[2] in RTL_EXPECTED]
    warns = [r for r in rows if r[0] == "warning" and r[2] not in RTL_EXPECTED]
    detail = ", ".join(f"{r[2]} {r[3]}" for r in errors) or "0 errors"
    if warns:
        detail += "; warnings: " + ", ".join(f"{r[2]} {r[3]}" for r in warns)
    if expected:
        detail += "; RTL-expected: " + ", ".join(f"{r[2]} {r[3]}" for r in expected)
    return pdk, cfg, "PASS" if not errors else "FAIL", detail


def main() -> int:
    ap = argparse.ArgumentParser(description="VC LP checks of the sram UPF")
    ap.add_argument("--pdk", choices=PDKS + ["all"], default="all")
    ap.add_argument("--cfg", choices=CFGS + ["all"], default="all")
    ap.add_argument("--jobs", type=int, default=3, help=f"parallel runs (max {MAX_JOBS})")
    args = ap.parse_args()
    pdks = PDKS if args.pdk == "all" else [args.pdk]
    cfgs = CFGS if args.cfg == "all" else [args.cfg]
    # Build the shared library caches once, before the threads start.
    for p in pdks:
        try:
            libraries(p)
        except FileNotFoundError as e:
            print(f"  ERROR: {e}")
    runs = [(p, c) for p in pdks for c in cfgs]
    with ThreadPoolExecutor(max(1, min(args.jobs, MAX_JOBS))) as ex:
        res = list(ex.map(lambda pc: run_one(*pc), runs))
    ok = all(r[2] == "PASS" for r in res)
    out_dir = os.path.join(ip_path(), "verification", "lp")
    os.makedirs(out_dir, exist_ok=True)
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [f"{'PASS' if ok else 'FAIL'}  lp_sram.py (VC LP, design/upf/sram_<pdk>.upf)  {stamp}"]
    lines += [f"{st:<5} {p:<7} {c:<5} {d}" for p, c, st, d in res]
    lines += ["", "RTL-expected tags (not counted): "
              + "; ".join(f"{k}: {v}" for k, v in RTL_EXPECTED.items())]
    with open(os.path.join(out_dir, "lp_results.log"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n" + "=" * 78)
    print("\n".join(lines))
    print("=" * 78)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
