#!/usr/bin/env python3
"""formal_bus_matrix.py — Formal verification runner for the bus_matrix IP block.

Two formal tools are supported:

  sby  SymbiYosys (open source). SV only, the .sby tasks in
       verification/formal/ (core and arbiter properties). Results:
           ${CLAUDE_BUS_MATRIX_PATH}/verification/formal/results.log
  vcf  Synopsys VC Formal (FPV). All four bus top-levels in BOTH SystemVerilog
       and VHDL-2008, checked with the same SVA checkers bound into the design
       (common bus checkers from ${IP_COMMON_PATH}/verification/formal/ on every
       master and slave port, plus the bus_matrix checkers in
       verification/formal/vcf/). Results:
           ${CLAUDE_BUS_MATRIX_PATH}/verification/formal/vcf/results.log
       Run directories: ${CLAUDE_BUS_MATRIX_PATH}/verification/work/vcf/<top>_<lang>/

--tool auto (default) picks vcf when it is on PATH (e.g. *.csun.edu) and sby
otherwise.

Usage:
    python3 verification/tools/formal_bus_matrix.py
    python3 verification/tools/formal_bus_matrix.py --tool sby
    python3 verification/tools/formal_bus_matrix.py --tool vcf --proto apb --lang vhdl
    python3 verification/tools/formal_bus_matrix.py --tool vcf --trace   # FSDB per failure
    python3 verification/tools/formal_bus_matrix.py --clean
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

PROTOCOLS = ["apb", "ahb", "axi4l", "wb"]
SBY_PATH = "/opt/oss-cad-suite/bin/sby"

# ---------------------------------------------------------------------------
# VC Formal job description (the reusable machinery lives in
# ${IP_COMMON_PATH}/verification/tools/claude_vcf.py)
# ---------------------------------------------------------------------------
SV_RTL = [
    "design/rtl/verilog/bus_matrix_pkg.sv",
    "design/rtl/verilog/bus_matrix_decoder.sv",
    "design/rtl/verilog/bus_matrix_arb.sv",
    "design/rtl/verilog/bus_matrix_core.sv",
]
VHDL_RTL = [
    "design/rtl/vhdl/bus_matrix_pkg.vhd",
    "design/rtl/vhdl/bus_matrix_decoder.vhd",
    "design/rtl/vhdl/bus_matrix_arb.vhd",
    "design/rtl/vhdl/bus_matrix_core.vhd",
]
VCF_CHECKERS = [
    "verification/formal/vcf/bus_matrix_core_fv.sv",
    "verification/formal/vcf/bus_matrix_arb_fv.sv",
]
VCF_WAIVERS = "verification/formal/vcf/bus_matrix_fv_waivers.txt"

# Stand-alone arbiter harness: both arbitration modes with 4 masters (the
# top-level jobs only see the default configuration).
ARB_TOP = "bus_matrix_arb_fv_top"


FV_CFG = "verification/formal/vcf/bus_matrix_fv_cfg.svh"
FV_CFG_CONSTS = ["BM_NUM_MASTERS", "BM_NUM_SLAVES", "BM_ARB_MODE",
                 "BM_M_PRIORITY", "BM_S_BASE", "BM_S_MASK"]


def write_fv_cfg(ip_path):
    """Generate bus_matrix_fv_cfg.svh from the SV bus_matrix_pkg.

    The checkers are bound into SV modules and VHDL entities alike, and an SV
    bind cannot see VHDL generics, so the configuration is passed to them as
    literals. Generating them from the package on every run keeps the
    checkers on the same (synthesized) configuration as the RTL defaults.
    """
    pkg = os.path.join(ip_path, "design", "rtl", "verilog", "bus_matrix_pkg.sv")
    with open(pkg) as fh:
        text = re.sub(r"//[^\n]*", "", fh.read())
    lines = [
        "// bus_matrix_fv_cfg.svh — GENERATED by verification/tools/formal_bus_matrix.py",
        "// from design/rtl/verilog/bus_matrix_pkg.sv. Do not edit.",
        "",
        "`ifndef BUS_MATRIX_FV_CFG_SVH",
        "`define BUS_MATRIX_FV_CFG_SVH",
        "",
    ]
    for name in FV_CFG_CONSTS:
        m = re.search(rf"localparam\b[^=;]*\b{name}\s*=\s*([^;]+);", text)
        if not m:
            raise SystemExit(f"ERROR: {name} not found in {pkg}")
        value = " ".join(m.group(1).split())
        lines.append(f"`define {name.replace('BM_', 'BM_FV_', 1)} {value}")
    lines += ["", "`endif // BUS_MATRIX_FV_CFG_SVH", ""]
    out = os.path.join(ip_path, FV_CFG)
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    return out


def import_claude_vcf(ip_path):
    """Import claude_vcf from ${IP_COMMON_PATH}/verification/tools."""
    common = os.environ.get(
        "IP_COMMON_PATH", os.path.join(ip_path, "..", "..", "common"))
    sys.path.insert(0, os.path.normpath(os.path.join(common, "verification", "tools")))
    import claude_vcf  # noqa: E402  (path set up above)
    return claude_vcf


# The AXI4-Lite master-port response bounds (B/R within M_WAIT cycles) need
# about 100 minutes to prove (2026-10-10: 6136 s for the SV job); at 30
# minutes they come back inconclusive. Every other job proves within 30M.
DEFAULT_MAX_TIME = "30M"
AXI4L_MAX_TIME = "3H"


def vcf_jobs(cv, ip_path, protos, langs, max_time):
    """Build one claude_vcf.VcfJob per (protocol, language).

    max_time=None selects the per-protocol default budget."""
    def ip(rel):
        return os.path.join(ip_path, rel)

    jobs = []
    if "arb" in protos:
        for lang in langs:
            ext = "vhd" if lang == "vhdl" else "sv"
            rtl_dir = "vhdl" if lang == "vhdl" else "verilog"
            jobs.append(cv.VcfJob(
                name=f"{ARB_TOP}_{lang}", top=ARB_TOP, lang=lang,
                # proto only supplies defaults that clock/reset override
                proto="apb",
                rtl_files=[ip(f"design/rtl/{rtl_dir}/bus_matrix_arb.{ext}"),
                           ip(f"verification/formal/vcf/{ARB_TOP}.{ext}")],
                sva_files=[ip("verification/formal/vcf/bus_matrix_arb_fv.sv"),
                           ip(f"verification/formal/vcf/{ARB_TOP}_bind.sv")],
                bind_module=f"{ARB_TOP}_bind",
                incdirs=[ip("verification/formal/vcf")],
                max_time=max_time or DEFAULT_MAX_TIME,
                clock="clk", reset="rst_n", reset_sense="low",
            ))
    for proto in [p for p in protos if p != "arb"]:
        top = f"bus_matrix_{proto}"
        for lang in langs:
            if lang == "vhdl":
                rtl = ([ip(f) for f in VHDL_RTL] +
                       [ip(f"design/rtl/vhdl/{top}_tgt.vhd"),
                        ip(f"design/rtl/vhdl/{top}_ini.vhd"),
                        ip(f"design/rtl/vhdl/{top}.vhd")])
            else:
                rtl = ([ip(f) for f in SV_RTL] +
                       [ip(f"design/rtl/verilog/{top}_tgt.sv"),
                        ip(f"design/rtl/verilog/{top}_ini.sv"),
                        ip(f"design/rtl/verilog/{top}.sv")])
            # Only the bus checker: the bus matrix has no register map.
            sva = ([cv.common_checker_files(proto)[0]] +
                   [ip(f) for f in VCF_CHECKERS] +
                   [ip(f"verification/formal/vcf/{top}_fv.sv"),
                    ip(f"verification/formal/vcf/{top}_fv_bind.sv")])
            jobs.append(cv.VcfJob(
                name=f"{top}_{lang}", top=top, lang=lang, proto=proto,
                rtl_files=rtl, sva_files=sva, bind_module=f"{top}_fv_bind",
                incdirs=[ip("verification/formal/vcf")],
                max_time=max_time or (AXI4L_MAX_TIME if proto == "axi4l"
                                      else DEFAULT_MAX_TIME),
                clock="clk", reset="rst_n", reset_sense="low",
            ))
    return jobs


def run_vcf_flow(ip_path, args):
    """Run VC Formal for the selected protocols/languages. Returns exit code."""
    cv = import_claude_vcf(ip_path)
    vcf = cv.find_vcf()
    if not vcf:
        print("ERROR: vcf (Synopsys VC Formal) not found on PATH.")
        return 1

    protos = PROTOCOLS + ["arb"] if args.proto == "all" else [args.proto]
    langs = cv.LANGS if args.lang == "all" else [args.lang]
    waivers = cv.load_waivers(os.path.join(ip_path, VCF_WAIVERS))
    work = os.path.join(ip_path, "verification", "work", "vcf")
    results_log = os.path.join(ip_path, "verification", "formal", "vcf", "results.log")

    print(f"[vcf] {cv.vcf_version(vcf)}")
    print(f"[vcf] Configuration: {os.path.relpath(write_fv_cfg(ip_path), ip_path)}")
    results = []
    for job in vcf_jobs(cv, ip_path, protos, langs, args.max_time):
        print(f"[vcf] Running {job.name} ...", flush=True)
        r = cv.run_job(job, os.path.join(work, job.name), waivers,
                       traces=args.trace, vcf=vcf)
        results.append(r)
        print(f"[vcf] {cv.summary_line(r)}")
        for p, why in r.failures:
            print(f"        {why:<24} {p.name}")
        # Per-run result, same shape as the other verification results logs.
        with open(os.path.join(work, job.name, "results.log"), "w") as fh:
            fh.write(("PASS" if r.passed else "FAIL") + "\n")

    overall = "PASS" if results and all(r.passed for r in results) else "FAIL"
    lines = [overall, f"Generated: {datetime.now().isoformat(timespec='seconds')}",
             f"Tool: {cv.vcf_version(vcf)}", ""]
    for r in results:
        lines.append(cv.summary_line(r))
        lines += [f"    FAIL   {why:<24} {p.name}" for p, why in r.failures]
        lines += [f"    WAIVED {p.name}  ({why})" for p, why in r.waived]
        lines.append(f"    report: {os.path.relpath(r.report_path, ip_path)}")
    with open(results_log, "w") as fh:
        fh.write("\n".join(lines) + "\n")

    print()
    print("============================================")
    print("VC Formal Results")
    print("============================================")
    for r in results:
        print(" ", cv.summary_line(r))
    print("============================================")
    print(f"Overall: {overall}")
    print(f"Results written to: {results_log}")
    return 0 if overall == "PASS" else 1


def find_sby():
    """Return path to sby, checking SBY_PATH then PATH."""
    if os.path.isfile(SBY_PATH) and os.access(SBY_PATH, os.X_OK):
        return SBY_PATH
    return shutil.which("sby")


def run_sby_flow(ip_path, formal_dir):
    """Run every .sby task in verification/formal/. Returns exit code."""
    sby = find_sby()
    results_log = os.path.join(formal_dir, "results.log")
    if not sby:
        print("ERROR: sby not found. Install oss-cad-suite or add sby to PATH.")
        return 1

    work_dir = os.path.join(formal_dir, "work")
    os.makedirs(work_dir, exist_ok=True)
    entries = []
    overall_pass = True
    for sby_path in sorted(Path(formal_dir).glob("*.sby")):
        name = sby_path.stem
        print(f"[formal] Running {name} ...")
        result = subprocess.run(
            [sby, "-f", "-d", os.path.join(work_dir, name), str(sby_path)],
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, cwd=formal_dir,
        )
        passed = result.returncode == 0
        overall_pass &= passed
        status = "PASS" if passed else "FAIL"
        print(f"[formal] {name}: {status}")
        entries.append(f"  {name}: {status}")
        entries += [f"    {line}" for line in result.stdout.splitlines()
                    if "DONE" in line or "failed assertion" in line or "Status:" in line]

    overall = "PASS" if overall_pass and entries else "FAIL"
    with open(results_log, "w") as fh:
        fh.write(f"{overall}\n")
        fh.write("\n".join(entries) + "\n")
    print(f"Results written to: {results_log}")
    return 0 if overall == "PASS" else 1


def do_clean(formal_dir):
    """Remove sby and VC Formal run directories and results logs."""
    print("Cleaning formal verification artifacts...")
    vcf_work = os.path.normpath(os.path.join(formal_dir, "..", "work", "vcf"))
    for d in [vcf_work, os.path.join(formal_dir, "work")]:
        if os.path.isdir(d):
            shutil.rmtree(d)
            print(f"  removed {d}")
    for results_log in [
        os.path.join(formal_dir, "results.log"),          # SymbiYosys
        os.path.join(formal_dir, "vcf", "results.log"),   # VC Formal
    ]:
        if os.path.isfile(results_log):
            os.remove(results_log)
            print(f"  removed {results_log}")
    print("Formal clean complete.")


def main():
    ip_path = os.environ.get("CLAUDE_BUS_MATRIX_PATH")
    if not ip_path:
        print("ERROR: CLAUDE_BUS_MATRIX_PATH is not set.")
        print("       Please run:  source IP/interface/bus_matrix/setup.sh")
        sys.exit(1)

    parser = argparse.ArgumentParser(
        description="Run formal verification checks on the bus_matrix IP block."
    )
    parser.add_argument(
        "--clean",
        action="store_true",
        help="Remove sby and VC Formal run directories and exit",
    )
    parser.add_argument(
        "--tool",
        choices=["auto", "sby", "vcf"],
        default="auto",
        help="formal tool: vcf if on PATH, else sby (default: %(default)s)",
    )
    parser.add_argument("--proto", choices=PROTOCOLS + ["arb", "all"], default="all",
                        help="bus top-level, or 'arb' for the stand-alone arbiter "
                             "harness (vcf only, default: %(default)s)")
    parser.add_argument("--lang", choices=["sv", "vhdl", "all"], default="all",
                        help="RTL language (vcf only, default: %(default)s)")
    parser.add_argument("--max-time", default=None,
                        help="VC Formal time budget per job (default: 30M, "
                             f"{AXI4L_MAX_TIME} for axi4l)")
    parser.add_argument("--trace", action="store_true",
                        help="VC Formal: save an FSDB counterexample per failure")
    args = parser.parse_args()

    formal_dir = os.path.join(ip_path, "verification", "formal")

    if args.clean:
        do_clean(formal_dir)
        sys.exit(0)

    tool = args.tool
    if tool == "auto":
        tool = "vcf" if shutil.which("vcf") else "sby"
    if tool == "vcf":
        sys.exit(run_vcf_flow(ip_path, args))
    sys.exit(run_sby_flow(ip_path, formal_dir))


if __name__ == "__main__":
    main()
